function resolveKoreanCompanyName(tickers,englishName){
 if(!tickers||typeof tickers[Symbol.iterator]!=='function'||
  typeof englishName!=='string')return {name:null,status:'INVALID_INPUT'};
 // Stored display HTML is escaped before review; normalize only for
 // issuer comparison, never insert the decoded string into public HTML.
 const name=englishName.toLowerCase().replace(/&(amp|quot|lt|gt|#39);/g,
  entity=>({'&amp;':'&','&quot;':'"','&lt;':'<','&gt;':'>','&#39;':"'"})[entity]);
 let knownTicker=false;
 for(const ticker of tickers){
  if(typeof ticker!=='string'||!Object.hasOwn(NAMES,ticker))continue;
  knownTicker=true;
  if(ENGLISH_HINTS[ticker]?.some(hint=>name.includes(hint)))
   return {name:NAMES[ticker],status:'MAPPED'};
 }
 return {name:null,status:knownTicker?'ISSUER_NAME_MISMATCH':'UNREGISTERED_TICKER'};
}

export function koreanCompanyName(tickers,englishName){
 return resolveKoreanCompanyName(tickers,englishName).name;
}

// Private PC diagnostics may distinguish a new symbol from an issuer-name
