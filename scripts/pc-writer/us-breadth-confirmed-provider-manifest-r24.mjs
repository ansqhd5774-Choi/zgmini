/**
 * R24: independently re-fetch MarketParquet-signed source bytes and compare
 * them to the already-stored, locally audited 251 daily files. READ ONLY.
 * The provider manifest has date/filename/size/URL, NOT a provider SHA256.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {auditFullMarketYearInventory,fullMarketYearSessions}
  from './us-breadth-confirmed-year-inventory-r22.mjs';
import {loadLocalProviders} from './local-env.mjs';
import {US_FULL_MARKET_YEAR_SESSIONS} from './us-breadth-confirmed-history-r21.mjs';
import {US_FULL_MARKET_PRICE_MODE} from '../../lib/market-breadth/us-marketparquet-confirmed-public-r2.mjs';

const MANIFEST_HOST='marketparquet.com';
const MAX_PARQUET_BYTES=30_000_000;
const sha256=data=>createHash('sha256').update(data).digest('hex');
const day=s=>typeof s==='string'&&/^\d{4}-\d{2}-\d{2}$/.test(s)
  &&Number.isFinite(Date.parse(s+'T00:00:00Z'))
  &&new Date(s+'T00:00:00Z').toISOString().slice(0,10)===s;
const validSize=n=>Number.isSafeInteger(n)&&n>=12&&n<=MAX_PARQUET_BYTES;

/** URL is never copied to results/errors/logs. */
export function validMarketParquetSignedUrl(value){
 try{
  const u=new URL(value);
  return u.protocol==='https:'&&!u.username&&!u.password&&!u.port&&!u.hash
    &&u.hostname.endsWith('.r2.cloudflarestorage.com')
    &&u.hostname.length>'.r2.cloudflarestorage.com'.length
    &&u.searchParams.has('X-Amz-Signature');
 }catch{return false;}
}

export function validateMarketParquetManifest(body,dates){
 if(!Array.isArray(dates)||!dates.length||dates.some(x=>!day(x))||
   !body||body.asset_type!=='stock_daily'||!Array.isArray(body.files)
   ||!Number.isSafeInteger(body.file_count)||body.file_count!==body.files.length
   ||body.start!==dates[0]||body.end!==dates.at(-1))
  return {ok:false,reason:'PROVIDER_MANIFEST_RANGE_INVALID'};
 const byDate=new Map(),requested=new Set(dates);
 for(const f of body.files){
  if(!day(f?.date)||f.filename!==`stock_daily_${f.date}.parquet`
    ||!validSize(f.file_size_bytes)||!validMarketParquetSignedUrl(f.download_url)
    ||byDate.has(f.date))return {ok:false,reason:'PROVIDER_MANIFEST_ENTRY_INVALID'};
  if(!requested.has(f.date))return {ok:false,reason:'PROVIDER_MANIFEST_UNEXPECTED_SESSION'};
  byDate.set(f.date,f);
 }
 const missing=dates.filter(d=>!byDate.has(d));
 if(missing.length)return {ok:false,reason:'PROVIDER_MANIFEST_MISSING_SESSION',
  missingDatesCount:missing.length,firstMissingDate:missing[0]};
 if(body.file_count!==dates.length)return {ok:false,reason:'PROVIDER_MANIFEST_RANGE_INVALID'};
 return {ok:true,files:dates.map(d=>byDate.get(d))};
}

function safeStatus(status,details={}){
 return {revision:'US_BREADTH_CONFIRMED_PROVIDER_PROVENANCE_R24',mode:'READ_ONLY',
  status,providerAuthenticityVerified:false,approvedR21ManifestEntries:null,
  candidateManifestEntries:null,remoteWrites:0,localWrites:0,schedulerChanges:0,
  ...details};
}

/**
 * A successful result is independent provider-byte evidence for *candidate*
 * R21 entries, not approval to write D1/overwrite any existing history.
 * Tests may supply a smaller sessionCount; the CLI always uses all 251 dates.
 */
export async function verifyMarketParquetProviderYear({
  dataRoot,pcHome,now=new Date(),sessionCount=US_FULL_MARKET_YEAR_SESSIONS,
  apiKey=process.env.MARKETPARQUET_API_KEY,fetchImpl=fetch,
}={}){
 if(typeof dataRoot!=='string'||!dataRoot||typeof pcHome!=='string'||!pcHome)
  return safeStatus('PC_OPERATING_ROOTS_NOT_CONFIGURED');
 let dates,inventory;
 try{
  dates=fullMarketYearSessions({now,sessionCount});
  inventory=auditFullMarketYearInventory({dataRoot,pcHome,now,sessionCount});
 }catch{return safeStatus('LOCAL_YEAR_INVENTORY_UNAVAILABLE');}
 const scope={requestedDates:dates.length,firstDate:dates[0],lastDate:dates.at(-1),
  localFound:inventory.found,localAuditShaMatched:inventory.localAuditShaMatched,
  providerCalls:0,verifiedDates:0};
 if(!inventory.localComplete)return safeStatus('LOCAL_YEAR_INVENTORY_INCOMPLETE',scope);
 if(!apiKey){
  try{apiKey=loadLocalProviders(pcHome).MARKETPARQUET_API_KEY;}catch{}
 }
 if(typeof apiKey!=='string'||!apiKey.trim())return safeStatus('PROVIDER_API_KEY_NOT_CONFIGURED',scope);
 // Manifest is obtained from the provider, never generated by re-hashing PC files.
 const api=new URL(`https://${MANIFEST_HOST}/api/v1/manifest/stock_daily`);
 api.searchParams.set('start',dates[0]);api.searchParams.set('end',dates.at(-1));
 let response,manifest;
 try{
  scope.providerCalls++;
  response=await fetchImpl(api,{headers:{Authorization:`Bearer ${apiKey}`},
   redirect:'manual',signal:AbortSignal.timeout(30000)});
  if(response.status===401||response.status===403)
   return safeStatus('PROVIDER_AUTH_OR_WINDOW_UNAVAILABLE',scope);
  if(response.status===429)return safeStatus('PROVIDER_RATE_LIMITED',scope);
  if(response.status!==200)return safeStatus('PROVIDER_MANIFEST_HTTP_UNAVAILABLE',scope);
  manifest=await response.json();
 }catch{return safeStatus('PROVIDER_MANIFEST_UNAVAILABLE',scope);}
 const checked=validateMarketParquetManifest(manifest,dates);
 if(!checked.ok)return safeStatus(checked.reason,{...scope,
  missingDatesCount:checked.missingDatesCount??null,
  firstMissingDate:checked.firstMissingDate??null});

 const candidates=[];
 for(const file of checked.files){
  const local=inventory.days[file.date];
  // Local files have already passed existing path-containment, audit SHA,
  // Parquet magic, duplicate and exact-date checks in the R22 inventory.
  if(local?.status!=='LOCAL_AUDIT_SHA_MATCH'||local.bytes!==file.file_size_bytes)
   return safeStatus('PROVIDER_LOCAL_FILE_SIZE_MISMATCH',{
    ...scope,firstFailDate:file.date});
  let download;
  try{
   scope.providerCalls++;
   download=await fetchImpl(file.download_url,{redirect:'manual',
    signal:AbortSignal.timeout(30000)});
   if(download.status!==200)return safeStatus('PROVIDER_SIGNED_DOWNLOAD_FAILED',{
    ...scope,firstFailDate:file.date});
   const headerSize=Number(download.headers?.get?.('content-length'));
   if(Number.isFinite(headerSize)&&headerSize>MAX_PARQUET_BYTES)
    return safeStatus('PROVIDER_SIGNED_DOWNLOAD_TOO_LARGE',{
     ...scope,firstFailDate:file.date});
   const bytes=Buffer.from(await download.arrayBuffer());
   if(bytes.length!==file.file_size_bytes||!validSize(bytes.length)
     ||bytes.toString('ascii',0,4)!=='PAR1'
     ||bytes.toString('ascii',bytes.length-4)!=='PAR1')
    return safeStatus('PROVIDER_SIGNED_BYTES_INVALID',{
     ...scope,firstFailDate:file.date});
   if(sha256(bytes)!==local.sha256)
    return safeStatus('PROVIDER_LOCAL_SHA_MISMATCH',{
     ...scope,firstFailDate:file.date});
  }catch{return safeStatus('PROVIDER_SIGNED_DOWNLOAD_UNAVAILABLE',{
   ...scope,firstFailDate:file.date});}
  // Only independent HTTPS provider bytes AND local stored SHA agree.
  candidates.push({date:file.date,provider:'MarketParquet',feed:'stock_daily',
   priceMode:US_FULL_MARKET_PRICE_MODE,complete:true,path:local.file,sha256:local.sha256});
  scope.verifiedDates++;
 }
 return {...safeStatus('PROVIDER_BYTES_MATCHED_ALL_DATES',scope),
  providerAuthenticityVerified:true,candidateManifestEntries:candidates,
  // A human/source-authority approval is still needed before R21 or D1 use.
  approvedR21ManifestEntries:null,independentApprovalRequired:true};
}

/** Never print signed URLs, secret auth or private per-file local paths. */
export function publicProviderYearSummary(report){
 const {candidateManifestEntries,approvedR21ManifestEntries,...safe}=report;
 return {...safe,candidateEntryCount:candidateManifestEntries?.length??0,
  approvedR21ManifestEntriesAvailable:Array.isArray(approvedR21ManifestEntries)};
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 if(process.argv.length!==3||!['--inspect','--verify-provider'].includes(process.argv[2]))
  throw Error('READ_ONLY_PROVIDER_ARGUMENTS_REQUIRED');
 const dataRoot=process.env.ZGMINI_DATA_ROOT??'E:/ZGmini/data';
 const pcHome=process.env.ZGMINI_PC_HOME??path.join(os.homedir(),'.zgmini','pc-writer');
 const verify=process.argv[2]==='--verify-provider';
 const report=verify?await verifyMarketParquetProviderYear({dataRoot,pcHome}):
  safeStatus('LOCAL_ONLY_PROVENANCE_NOT_VERIFIED',
    (()=>{const inventory=auditFullMarketYearInventory({dataRoot,pcHome});
      return {requestedDates:inventory.requestedDates,firstDate:inventory.firstDate,
       lastDate:inventory.lastDate,localFound:inventory.found,
       localAuditShaMatched:inventory.localAuditShaMatched,providerCalls:0};})());
 process.stdout.write(JSON.stringify(publicProviderYearSummary(report))+'\n');
}
