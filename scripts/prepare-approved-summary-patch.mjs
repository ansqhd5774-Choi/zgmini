import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {execFileSync,spawnSync} from 'node:child_process';
import assert from 'node:assert/strict';
const file='app/dashboard-ui.tsx';
const baseline=execFileSync('git',['show','de0504f191ab2ba5e0bdbdebd312f162f25f035e:'+file],{encoding:'utf8'});
assert.equal(readFileSync(file,'utf8').replaceAll('\r\n','\n'),baseline.replaceAll('\r\n','\n'));
const start=baseline.indexOf('<div className="zg-r55-summary-top"');
const end=baseline.indexOf('<div className="zg-r55-summary-chart">',start);
assert(start>0&&end>start);
const segment=baseline.slice(start,end);
assert.equal((segment.match(/zg-r55-gauge-ring/g)||[]).length,1);
const next=segment.replace(/^.*className="zg-r55-gauge-ring".*\r?\n/m,'').replace(/^.*<span>\{overallStatus\}<\/span>.*\r?\n/m,'').replace('overallScore===null?overallStatus:',"overallScore===null?'자료 없음':");
assert(!next.includes('gauge-ring')&&!next.includes('overallStatus'));
assert(next.includes('Math.round(overallScore)'));
mkdirSync('work/r3-ui',{recursive:true});
writeFileSync('work/r3-ui/before.tsx',baseline);
writeFileSync('work/r3-ui/after.tsx',baseline.slice(0,start)+next+baseline.slice(end));
const result=spawnSync('git',['diff','--no-index','--','work/r3-ui/before.tsx','work/r3-ui/after.tsx'],{encoding:'utf8'});
assert.equal(result.status,1);
const patch=result.stdout.replaceAll('a/work/r3-ui/before.tsx','a/'+file).replaceAll('b/work/r3-ui/after.tsx','b/'+file);
writeFileSync('docs/migration/r3/approved-summary-numbers-only.patch',patch);
execFileSync('git',['apply','--check','docs/migration/r3/approved-summary-numbers-only.patch']);
console.log('PASS: isolated summary patch applies to Production baseline; application source unchanged.');
